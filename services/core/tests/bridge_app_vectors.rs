//! The bridge web app's test vectors for the core's derivations (F-018, T-018-13; `REQ-ST-1`): the
//! mint's on-chain reference and the payout reference of an unassociated arrival's refund, from a
//! coordinate (`refs::mint_reference`, `refs::unassociated_refund_reference`), and the 32-byte
//! account of an issuing-network address (`refs::account32`). The app derives the same in
//! TypeScript (`apps/bridge/src/lib/`) and checks itself against
//! `apps/bridge/test/vectors/core-refs.json`; this test computes that file and fails when it
//! differs, so the two never drift.
//!
//! Regenerate it after a deliberate change to a derivation (which is itself a breaking change):
//!
//!   BEZENT_WRITE_VECTORS=1 cargo test -p bezent-core-service --test bridge_app_vectors

use bezent_core_service::refs::{
    Coordinate, account32, mint_reference, unassociated_refund_reference,
};
use serde_json::{Value, json};

const FIXTURE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../apps/bridge/test/vectors/core-refs.json"
);

/// The same coordinates as `services/ingress/src/refs_bridge_vectors.rs`.
fn coordinates() -> Vec<(&'static str, u64, Vec<u8>, &'static str, u32)> {
    vec![
        ("origin-a", 7, vec![0xaa], "log", 0),
        ("origin-a", 7, vec![0xaa], "log", 1),
        ("origin-a", 1, vec![0xab, 0x01], "transaction", 3),
        ("polygon", 96_983_980, vec![0x11; 32], "log", u32::MAX),
        ("polygon", 0, (0u8..32).collect(), "log", 0),
        (
            "polygon-amoy",
            29_000_123,
            (0u8..32).rev().collect(),
            "log",
            42,
        ),
        (
            "polygon",
            u64::from(u32::MAX) + 1,
            vec![0xff; 32],
            "log",
            256,
        ),
        ("polygon", i64::MAX as u64, vec![0x5a; 32], "log", 7),
    ]
}

/// Issuing-network addresses: Alice and Bob in Kreivo's prefix (2) and the generic one (42), a
/// broken checksum, a two-byte prefix, raw hex and strings that are no address. `null` is "not an
/// account".
const ADDRESSES: &[&str] = &[
    "HNZata7iMYWmk5RvZRTiAsSDhV8366zq2YGb3tLH5Upf74F",
    "FoQJpPyadYccjavVdTWxpxU7rUEaYhfLCPwXgkfD6Zat9QP",
    "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY",
    "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQZ",
    "HNZata7iMYWmk5RvZRTiAsSDhV8366zq2YGb3tLH5Upf74G",
    "cEYtw6AVMB27hFUs4gVukajLM7GqxwxUfJkbPY3rNToHMcCgb",
    "0xd43593c715fdd31c61141abd04a99fd6822c8558854ccde39a5684e7a56da27d",
    "",
    "not an address",
];

fn vectors() -> Value {
    let rows: Vec<Value> = coordinates()
        .into_iter()
        .map(|(network, block, hash, kind, index)| {
            let c = Coordinate {
                network: network.into(),
                block_number: i64::try_from(block).unwrap(),
                block_hash: hash.clone(),
                position_kind: kind.into(),
                position_index: i64::from(index),
            };
            json!({
                "coordinate": {
                    "network": network,
                    "block_number": block.to_string(),
                    "block_hash": format!("0x{}", hex::encode(&hash)),
                    "position_kind": kind,
                    "position_index": index,
                },
                "mint_reference": format!("0x{}", hex::encode(mint_reference(&c))),
                "unassociated_refund_reference":
                    format!("0x{}", hex::encode(unassociated_refund_reference(&c))),
            })
        })
        .collect();
    let accounts: Vec<Value> = ADDRESSES
        .iter()
        .map(|a| {
            json!({
                "address": a,
                "account": account32(a).map(|b| format!("0x{}", hex::encode(b))),
            })
        })
        .collect();
    json!({
        "about": "Generated by services/core/tests/bridge_app_vectors.rs from refs::mint_reference, \
                  refs::unassociated_refund_reference and refs::account32. Do not edit: run \
                  BEZENT_WRITE_VECTORS=1 cargo test -p bezent-core-service --test bridge_app_vectors.",
        "vectors": rows,
        "accounts": accounts,
    })
}

#[test]
fn req_st_1_bridge_app_reference_vectors_match_the_core() {
    let want = vectors();
    if std::env::var_os("BEZENT_WRITE_VECTORS").is_some() {
        let text = serde_json::to_string_pretty(&want).unwrap() + "\n";
        std::fs::write(FIXTURE, text).unwrap();
        return;
    }
    let have: Value = serde_json::from_str(
        &std::fs::read_to_string(FIXTURE).unwrap_or_else(|e| panic!("{FIXTURE}: {e}")),
    )
    .unwrap();
    assert_eq!(
        have, want,
        "apps/bridge/test/vectors/core-refs.json is stale: the TypeScript derivation would drift"
    );
}
