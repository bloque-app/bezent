//! The bridge web app's test vectors for the ingress's bridge references (F-018, T-018-13;
//! `REQ-ST-1`). The app derives `bz-d-…` and `bz-u-…` in TypeScript (`apps/bridge/src/lib/refs.ts`)
//! and checks itself against `apps/bridge/test/vectors/ingress-refs.json`; this test computes that
//! file from [`super::deposit`] and [`super::unassociated_refund`] and fails when it differs, so the
//! two derivations never drift.
//!
//! Regenerate it after a deliberate change to a derivation (which is itself a breaking change):
//!
//!   BEZENT_WRITE_VECTORS=1 cargo test -p bezent-ingress --lib bridge_vectors

use super::{deposit, unassociated_refund};
use bezent_core::{BlockHash, Coordinate, NetworkId, Position};
use serde_json::{Value, json};

const FIXTURE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../apps/bridge/test/vectors/ingress-refs.json"
);

/// The coordinates the vectors cover: the store's pinned ones (`refs::tests`), a 32-byte hash,
/// the largest block number and log index, a transaction position and the test networks' ids. The
/// same list is in `services/core/tests/bridge_app_vectors.rs`.
fn coordinates() -> Vec<(&'static str, u64, Vec<u8>, &'static str, u32)> {
    vec![
        ("origin-a", 7, vec![0xaa], "log", 0),
        ("origin-a", 7, vec![0xaa], "log", 1),
        ("origin-a", 1, vec![0xab, 0x01], "transaction", 3),
        ("polygon", 96_983_980, vec![0x11; 32], "log", u32::MAX),
        ("polygon", 0, (0u8..32).collect(), "log", 0),
        (
            "polygon-amoy",
            29_000_123,
            (0u8..32).rev().collect(),
            "log",
            42,
        ),
        (
            "polygon",
            u64::from(u32::MAX) + 1,
            vec![0xff; 32],
            "log",
            256,
        ),
        ("polygon", i64::MAX as u64, vec![0x5a; 32], "log", 7),
    ]
}

fn vectors() -> Value {
    let rows: Vec<Value> = coordinates()
        .into_iter()
        .map(|(network, block, hash, kind, index)| {
            let c = Coordinate {
                network: NetworkId::new(network).unwrap(),
                block_number: block,
                block_hash: BlockHash::new(hash.clone()),
                position: match kind {
                    "log" => Position::Log(index),
                    _ => Position::Transaction(index),
                },
            };
            json!({
                "coordinate": {
                    "network": network,
                    "block_number": block.to_string(),
                    "block_hash": format!("0x{}", hex::encode(&hash)),
                    "position_kind": kind,
                    "position_index": index,
                },
                "deposit": deposit(&c),
                "unassociated_refund": unassociated_refund(&c),
            })
        })
        .collect();
    json!({
        "about": "Generated by services/ingress/src/refs_bridge_vectors.rs from refs::deposit and \
                  refs::unassociated_refund. Do not edit: run BEZENT_WRITE_VECTORS=1 cargo test -p \
                  bezent-ingress --lib bridge_vectors.",
        "vectors": rows,
    })
}

#[test]
fn req_st_1_bridge_app_reference_vectors_match_the_ingress() {
    let want = vectors();
    if std::env::var_os("BEZENT_WRITE_VECTORS").is_some() {
        let text = serde_json::to_string_pretty(&want).unwrap() + "\n";
        std::fs::write(FIXTURE, text).unwrap();
        return;
    }
    let have: Value = serde_json::from_str(
        &std::fs::read_to_string(FIXTURE).unwrap_or_else(|e| panic!("{FIXTURE}: {e}")),
    )
    .unwrap();
    assert_eq!(
        have, want,
        "apps/bridge/test/vectors/ingress-refs.json is stale: the TypeScript derivation would drift"
    );
}
