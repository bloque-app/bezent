/// The issuing test network.
pub const NETWORK: &str = "kreivo-test";
/// Its genesis.
pub const GENESIS: [u8; 32] = [0x6b; 32];
/// The contract's account.
pub const CONTRACT: AccountId32 = [0xc0; 32];
/// The token the endpoint presents to the signer.
pub const TOKEN: &str = "endpoint-token-for-tests";

/// The 32-byte seed of test key `id`.
pub fn seed(id: &str) -> [u8; 32] {
    Sha256::digest(format!("bezent kreivo-endpoint test key {id}")).into()
}

/// A fresh directory under the system's temporary directory.
pub fn temp_dir() -> PathBuf {
    static N: AtomicU32 = AtomicU32::new(0);
    let dir = std::env::temp_dir().join(format!(
        "bzk-{}-{}",
        std::process::id(),
        N.fetch_add(1, Ordering::Relaxed)
    ));
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// The current process's user id.
pub fn my_uid() -> u32 {
    let (a, _b) = std::os::unix::net::UnixStream::pair().unwrap();
    a.set_nonblocking(true).unwrap();
    tokio::net::UnixStream::from_std(a)
        .unwrap()
        .peer_cred()
        .unwrap()
        .uid()
}

/// The test-only password of the logins these tests make.
const LOGIN_PASSWORD: &str = "test-only-kreivo-endpoint-tests-login";

/// A pool on `admin`'s database logged in as a login of its own that is a member of `role` and of
/// nothing else, as each service's login is: one pool, one login, never a switched role (#27,
/// #46). Logins are created once per server.
pub async fn role_pool(admin: &PgPool, role: &'static str) -> PgPool {
    bezent_store::login::connect_login(
        admin,
        &format!("kreivo_endpoint_tests_{role}"),
        role,
        LOGIN_PASSWORD,
        PgPoolOptions::new().max_connections(3),
    )
    .await
    .unwrap_or_else(|e| panic!("{e}"))
}

/// The endpoint over a test database, the in-memory chain and an in-process signer.
pub struct Fixture {
    /// The migration owner's pool, for reading anything.
    pub admin: PgPool,
    /// The endpoint's pool: its own login, a member of `bezent_kreivo_endpoint` only (review S1;
    /// issues #30, #46).
    pub endpoint: PgPool,
    /// Another service's pool: the ingress's login.
    pub service: PgPool,
    /// The core's pool: it records intents.
    pub core: PgPool,
    /// The chain.
    pub chain: FakeChain,
    /// The lane.
    pub lane: Lane,
    /// The signer link.
    pub link: SignerLink,
    /// The test key backend, for signing outside the signer.
    pub keys: FileBackend,
    /// How to connect again.
    pub connect: PgConnectOptions,
}

impl Fixture {
    /// Builds the fixture, with chain blocks `1..=blocks` produced and final.
    pub async fn new(pool: PgPoolOptions, connect: PgConnectOptions) -> Fixture {
        let admin = bezent_store::login::guard(pool)
            .connect_with(connect.clone())
            .await
            .unwrap();
        // The endpoint records only the networks its role covers: the issuing network (#30).
        sqlx::Executor::execute(
            &admin,
            format!(
                "INSERT INTO networks (network, role, address_format) \
                 VALUES ('{NETWORK}', 'issuing', 'ss58') ON CONFLICT DO NOTHING"
            )
            .as_str(),
        )
        .await
        .unwrap();
        let dir = temp_dir();
        let keys_path = dir.join("keys.json");
        std::fs::write(
            &keys_path,
            serde_json::to_vec(&serde_json::json!({
                "comment": "TEST KEYS, generated by the endpoint's tests",
                "environment": "test",
                "keys": [{"id": "kreivo-mint", "scheme": "sr25519",
                          "seed": format!("0x{}", hex::encode(seed("kreivo-mint")))}],
            }))
            .unwrap(),
        )
        .unwrap();
        let uid = my_uid();
        let caller = Caller {
            name: "kreivo-endpoint".into(),
            uid,
            token_sha256: vec![hex::encode(Sha256::digest(TOKEN.as_bytes()))],
        };
        let config_path = dir.join("signer.json");
        std::fs::write(
            &config_path,
            serde_json::to_vec(&serde_json::json!({
                "socket": dir.join("s.sock"),
                "callers": [{"name": caller.name, "uid": uid, "token_sha256": caller.token_sha256}],
                "networks": [{"id": NETWORK, "environment": "test", "issuing": true,
                              "contract_account": format!("0x{}", hex::encode(CONTRACT)),
                              // What a mint's bytes must carry (audit must-fix 2).
                              "genesis": format!("0x{}", hex::encode(GENESIS))}],
                "keys": {"backend": "file", "path": keys_path},
                "bindings": [{"key": "kreivo-mint", "network": NETWORK,
                              "purposes": ["mint", "refund-mint"],
                              "window_cap": "1000000000000", "window_seconds": 3600}],
            }))
            .unwrap(),
        )
        .unwrap();
        let config = Config::load(&config_path).unwrap();
        let backend = FileBackend::load(&keys_path).unwrap();
        let policy = config.policy(&backend).unwrap();
        let signer_pool = role_pool(&admin, bezent_store::SIGNER_ROLE).await;
        let (log, _captured) = Log::capture();
        let signer = Arc::new(Signer::new(
            signer_pool,
            policy,
            FileBackend::load(&keys_path).unwrap(),
            log,
        ));
        let socket = dir.join("s.sock");
        let listener = link::bind(&socket).unwrap();
        tokio::spawn(link::serve(
            listener,
            Arc::new(Callers::sharing_the_signer_uid_in_tests(&[caller])),
            signer,
        ));

        let public_key = backend.public_key("kreivo-mint").unwrap();
        let chain = FakeChain::new(GENESIS, CONTRACT);
        let account = chain.register_key(Scheme::Sr25519, &public_key);
        chain.advance(3);
        Fixture {
            endpoint: role_pool(&admin, bezent_store::KREIVO_ENDPOINT_ROLE).await,
            service: role_pool(&admin, bezent_store::INGRESS_ROLE).await,
            core: role_pool(&admin, bezent_store::CORE_ROLE).await,
            admin,
            chain,
            lane: Lane {
                key: "kreivo-mint".into(),
                scheme: Scheme::Sr25519,
                public_key,
                account,
            },
            link: SignerLink {
                socket,
                uid,
                token: TOKEN.into(),
            },
            keys: backend,
            connect,
        }
    }

    /// The follower.
    pub fn follower(&self) -> Follower<'_, FakeChain> {
        Follower {
            chain: &self.chain,
            pool: &self.endpoint,
            network: NETWORK,
            contract: CONTRACT,
            start_block: 1,
            first_seq: 0,
            max_range: 4,
            max_walk: 10_000,
        }
    }

    /// The submitter.
    pub fn submitter(&self) -> Submitter<'_, FakeChain> {
        Submitter {
            chain: &self.chain,
            pool: &self.endpoint,
            network: NETWORK,
            genesis: GENESIS,
            contract: CONTRACT,
            lane: &self.lane,
            signer: &self.link,
        }
    }

    /// The prover.
    pub fn prover(&self) -> Prover<'_, FakeChain> {
        Prover {
            chain: &self.chain,
            pool: &self.endpoint,
            network: NETWORK,
            contract: CONTRACT,
            lane: &self.lane,
            max_walk: 10_000,
        }
    }

    /// Records a mint order as the core would.
    pub async fn order_mint(&self, reference: [u8; 32], to: AccountId32, amount: u128) -> i64 {
        self.order(
            "mint",
            reference,
            serde_json::json!({
                "order": {"asset": "Here(101)", "to": format!("0x{}", hex::encode(to))},
                "amount": amount.to_string(),
            }),
        )
        .await
    }

    /// Records a refund-mint order as the core would.
    pub async fn order_refund(
        &self,
        reference: [u8; 32],
        redeemer: AccountId32,
        amount: u128,
    ) -> i64 {
        self.order(
            "refund-mint",
            reference,
            serde_json::json!({
                "order": {"redeemer": format!("0x{}", hex::encode(redeemer))},
                "amount": amount.to_string(),
            }),
        )
        .await
    }

    async fn order(&self, purpose: &str, reference: [u8; 32], payload: serde_json::Value) -> i64 {
        self.intent(purpose, &reference, payload).await
    }

    /// Records an intent as the core, and returns its id.
    pub async fn intent(&self, purpose: &str, reference: &[u8], payload: serde_json::Value) -> i64 {
        sqlx::query_scalar(
            "INSERT INTO intents (network, purpose, on_chain_reference, payload) \
             VALUES ($1, $2, $3, $4::text::jsonb) RETURNING id",
        )
        .bind(NETWORK)
        .bind(purpose)
        .bind(reference)
        .bind(payload.to_string())
        // A delivery order rests on a transfer and a final observation the store checks (0049, the
        // audit of PR #56): these tests are the endpoint's, with no transfer behind the order, so
        // an order is recorded as the migration owner, as a drill would. Every other intent is the
        // core's login's.
        .fetch_one(
            if payload.get("order").is_some() && payload.get("prepared").is_none() {
                &self.admin
            } else {
                &self.core
            },
        )
        .await
        .expect("the core records the intent")
    }

    /// Records an intent that the store's signing-intent check (0037, PR #39 third review MF-A)
    /// refuses: first proves the refusal, then records it with the check off, as the migration
    /// owner, the way a core that wrote past the store would, so a test reaches the endpoint's own
    /// check behind the store's.
    pub async fn intent_past_the_store(
        &self,
        purpose: &str,
        reference: &[u8],
        payload: serde_json::Value,
    ) -> i64 {
        let insert = "INSERT INTO intents (network, purpose, on_chain_reference, payload) \
                      VALUES ($1, $2, $3, $4::text::jsonb) RETURNING id";
        let refused = sqlx::query_scalar::<_, i64>(insert)
            .bind(NETWORK)
            .bind(purpose)
            .bind(reference)
            .bind(payload.to_string())
            .fetch_one(&self.core)
            .await
            .expect_err("the store recorded a signing intent its check refuses");
        assert_eq!(
            refused
                .as_database_error()
                .and_then(|d| d.code())
                .as_deref(),
            Some(bezent_store::REFUSAL_SQLSTATE),
            "{refused}"
        );
        let mut tx = self.admin.begin().await.unwrap();
        sqlx::raw_sql("ALTER TABLE intents DISABLE TRIGGER intents_guard_prepared")
            .execute(&mut *tx)
            .await
            .unwrap();
        let id: i64 = sqlx::query_scalar(insert)
            .bind(NETWORK)
            .bind(purpose)
            .bind(reference)
            .bind(payload.to_string())
            .fetch_one(&mut *tx)
            .await
            .expect("record the intent past the store's check");
        sqlx::raw_sql("ALTER TABLE intents ENABLE TRIGGER intents_guard_prepared")
            .execute(&mut *tx)
            .await
            .unwrap();
        tx.commit().await.unwrap();
        id
    }

    /// Records the signing intent for a prepared transaction, as the core would (`F-003`).
    pub async fn signing_intent(
        &self,
        purpose: &str,
        reference: [u8; 32],
        prepared: &Prepared,
        amount: u128,
    ) -> i64 {
        let Prepared::Ready { id, message, .. } = prepared else {
            panic!("not ready: {prepared:?}");
        };
        self.intent(
            purpose,
            &reference,
            signing_intent_payload(*id, message, amount),
        )
        .await
    }

    /// How many signatures the signer recorded.
    pub async fn signatures(&self) -> i64 {
        sqlx::query_scalar("SELECT count(*) FROM signatures")
            .fetch_one(&self.admin)
            .await
            .unwrap()
    }

    /// A count from the admin pool.
    pub async fn count(&self, sql: &str) -> i64 {
        sqlx::query_scalar(sql)
            .fetch_one(&self.admin)
            .await
            .unwrap()
    }
}
